create table services (id bigint generated by default as identity primary key, name text not null);
create table users (
    id bigint generated by default as identity primary key,
    service_id bigint not null references services(id),
    username varchar(100) not null unique,
    name text not null,
    password_hash text not null,
    role text not null check (role in ('INITIATOR','OPERATOR')),
    unique(id,service_id)
);
create table workers (
    id bigint generated by default as identity primary key,
    name text not null,
    endpoint text not null check (endpoint ~ '^https?://'),
    created_at timestamptz not null default now()
);
create table tasks (
    id bigint generated by default as identity primary key,
    service_id bigint not null references services(id),
    author_id bigint not null,
    operator_id bigint,
    worker_id bigint references workers(id),
    active_operation_id uuid,
    name varchar(100) not null check (name ~ '^[A-Za-zА-Яа-яЁё0-9._-]{1,100}$'),
    description varchar(1000) not null,
    type text not null check (type in ('process','research','collect')),
    state text not null check (state in ('NEW','WAITING_TO_SEND','EXECUTING','AWAITING_ACCEPTANCE','RETURNED','COMPLETED')),
    version bigint not null check (version>=0),
    foreign key(author_id,service_id) references users(id,service_id),
    foreign key(operator_id,service_id) references users(id,service_id),
    check ((state='NEW' and operator_id is null) or (state<>'NEW' and operator_id is not null))
);
create index tasks_scope_type on tasks(service_id,type,id desc);
create index tasks_author on tasks(author_id,id desc);
create index tasks_load on tasks(operator_id) where state<>'COMPLETED';
create table operations (
    id uuid primary key,
    task_id bigint not null references tasks(id),
    business_key text not null unique,
    worker_id bigint not null references workers(id),
    external_id text,
    document jsonb not null,
    unique(id,task_id)
);
alter table tasks add foreign key(active_operation_id,id) references operations(id,task_id) deferrable initially deferred;
create table exchange_jobs (
    id uuid primary key default gen_random_uuid(),
    operation_id uuid not null unique references operations(id),
    kind text not null check (kind in ('POST','GET','RECONCILE','AUTO_RECONCILE')),
    failures integer not null default 0 check (failures between 0 and 5),
    due_at timestamptz not null,
    lease_token uuid,
    locked_until timestamptz,
    started_at timestamptz,
    check ((lease_token is null) = (locked_until is null))
);
create index exchange_jobs_due on exchange_jobs(due_at);
create table exchange_attempts (
    id bigint generated always as identity primary key,
    operation_id uuid not null references operations(id),
    started_at timestamptz not null,
    finished_at timestamptz not null,
    status integer not null,
    network_failure boolean not null,
    response text not null
);
create table problems (
    id bigint generated always as identity primary key,
    task_id bigint not null references tasks(id),
    operation_id uuid not null references operations(id),
    kind text not null,
    at timestamptz not null,
    local_observation jsonb not null,
    external_observation text not null,
    resolved_at timestamptz,
    resolved_by bigint references users(id),
    decision text
);
create index problems_open on problems(task_id) where resolved_at is null;
create table reconciliations (
    id bigint generated always as identity primary key,
    operation_id uuid not null references operations(id),
    at timestamptz not null,
    local_observation jsonb not null,
    external_observation text not null
);
create table audit (
    id bigint generated always as identity primary key,
    task_id bigint not null references tasks(id),
    actor_id bigint references users(id),
    at timestamptz not null,
    action text not null,
    details jsonb not null
);
create index audit_task on audit(task_id,id);
create table api_requests (
    user_id bigint not null references users(id),
    key varchar(200) not null,
    fingerprint text not null,
    response jsonb not null,
    created_at timestamptz not null default now(),
    primary key(user_id,key)
);
create table spring_session (
    primary_id char(36) not null primary key,
    session_id char(36) not null unique,
    creation_time bigint not null,
    last_access_time bigint not null,
    max_inactive_interval integer not null,
    expiry_time bigint not null,
    principal_name varchar(100)
);
create index spring_session_expiry on spring_session(expiry_time);
create index spring_session_principal on spring_session(principal_name);
create table spring_session_attributes (
    session_primary_id char(36) not null references spring_session(primary_id) on delete cascade,
    attribute_name varchar(200) not null,
    attribute_bytes bytea not null,
    primary key(session_primary_id,attribute_name)
);
